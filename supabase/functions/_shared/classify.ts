export function normalizeText(s: string | undefined | null): string {
  return (s ?? "").normalize("NFD").replace(/\p{M}/gu, "").toLowerCase();
}

function escapeRegExp(s: string) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

// Precompila expresiones con límites de palabra para evitar falsos positivos
// (p. ej. «sig» dentro de «siguiente», «ai» dentro de «aire»).
const KEYWORD_REGEX: [Exclude<CategorySlug, "otros">, string, RegExp][] = [];
for (const [slug, words] of Object.entries(KEYWORDS) as [Exclude<CategorySlug, "otros">, string[]][]) {
  for (const w of words) {
    KEYWORD_REGEX.push([slug, w, new RegExp(`(^|[^a-z0-9])${escapeRegExp(w)}($|[^a-z0-9])`)]);
  }
}

function domainMatches(domain: string, url: string, rule: string): boolean {
  if (rule.includes("/")) return url.includes(rule);
  return domain === rule || domain.endsWith(`.${rule}`);
}

export function classify(input: ClassifyInput): ClassifyResult {
  const scores = new Map<CategorySlug, number>();
  const reasons: string[] = [];
  const add = (slug: CategorySlug, pts: number, why: string) => {
    scores.set(slug, (scores.get(slug) ?? 0) + pts);
    reasons.push(`${slug}+${pts}: ${why}`);
  };

  const domain = input.domain.toLowerCase();
  const urlNoProto = normalizeText(input.url.replace(/^https?:\/\/(www\.)?/i, ""));

  if (input.hasJobPosting) add("empleo", 8, "datos estructurados JobPosting");

  for (const [slug, rules] of Object.entries(DOMAIN_RULES) as [Exclude<CategorySlug, "otros">, string[]][]) {
    for (const rule of rules) {
      if (domainMatches(domain, urlNoProto, rule)) {
        add(slug, 5, `dominio ${rule}`);
        break;
      }
    }
  }

  // Rutas típicas de ofertas laborales en sitios generales (LinkedIn, webs de empresas).
  if (/(^|\/)(jobs?|empleos?|trabajos?|careers?|vacantes?|convocatorias?)(\/|$|\?|-)/.test(urlNoProto)) {
    add("empleo", 4, "ruta de oferta laboral");
  }
  if (/(^|\/)(courses?|cursos?|learn|tutorials?|tutoriales?)(\/|$|\?|-)/.test(urlNoProto)) {
    add("formacion", 2, "ruta de curso o tutorial");
  }

  const fields: [string, number][] = [
    [normalizeText(input.title), 2],
    [normalizeText(`${input.description ?? ""} ${input.keywords ?? ""} ${input.siteName ?? ""}`), 1],
    [urlNoProto.replace(/[/_.?=&-]+/g, " "), 1],
  ];

  for (const [slug, word, re] of KEYWORD_REGEX) {
    let best = 0;
    for (const [text, weight] of fields) {
      if (text && re.test(text)) best = Math.max(best, weight);
    }
    if (best) add(slug, best, `«${word}»`);
  }

  if (input.ogType && normalizeText(input.ogType) === "article") add("noticias", 0.5, "og:type article");

  let bestSlug: CategorySlug = "otros";
  let bestScore = 0;
  for (const slug of TIE_ORDER) {
    const s = scores.get(slug) ?? 0;
    if (s > bestScore) {
      bestScore = s;
      bestSlug = slug;
    }
  }

  // Umbral mínimo: con menos de 2 puntos no hay evidencia suficiente.
  if (bestScore < 2) return { slug: "otros", score: bestScore, confident: false, reasons };
  return { slug: bestSlug, score: bestScore, confident: bestScore >= 5, reasons };
}
